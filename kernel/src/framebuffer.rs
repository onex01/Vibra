        // и на реальном железе картинка была бы «размазанной». Такие режимы
        // у UEFI GOP не встречаются, но лучше явно предупредить в логе.
        if framebuffer.bpp != 32 {
            crate::println!(
                "[FB] WARNING: {}-bpp framebuffer; console drawing assumes 32 bpp",
                framebuffer.bpp
            );
        }

        let mut console = Console {
            fb_addr,
            pitch,
            width,
            height,
            cols: width / FONT_WIDTH,
            rows: height / FONT_HEIGHT,
            cursor_col: 0,
            cursor_row: 0,
            fg_color: COLOR_VIBRA_FG,
            bg_color: COLOR_VIBRA_BG,
            pixel_format,
            back_buffer: None,
            back_buffer_ptr: core::ptr::null_mut(),
            back_buffer_size: 0,
            virtual_width: 0,
            virtual_height: 0,
            scale_x: 0,
            scale_y: 0,
            cursor_blink_state: true,
            cursor_painted: false,
            cursor_painted_at: (0, 0),
            last_blink_ms: 0,
            cells: Vec::new(),
            staging: Vec::new(),
            painted_max: 0,
            pending: false,
            last_flush_ms: 0,
            wc_pages: 0,
            wc_already: 0,
            wc_unmapped: 0,
            wc_leaf_flags: 0,
            mtrr_type: 0xFF,
            mtrr_before: 0xFF,
            pat_ok: false,
            wc_report_pending: false,
            cells_valid: core::cell::Cell::new(true),
            fb_is_ram: core::cell::Cell::new(probe_framebuffer_is_ram(
                fb_addr,
                pitch,
                height,
            )),
        };

        console.reset_cells();
        console.clear();
