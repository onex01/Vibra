/// Перевод Unicode-символов в CP437-коды шрифта.
///
/// Консоль использует CP437, поэтому рамки, блоки и стрелки нужно отдавать
/// их однобайтовыми кодами. Неизвестный символ → 0 (пустая ячейка).
fn cp437_index(ch: char) -> u8 {
    match ch {
        // Рамки
        '\u{2500}' => 0xC4, // ─
        '\u{2502}' => 0xB3, // │
        '\u{250C}' => 0xDA, // ┌
        '\u{2510}' => 0xBF, // ┐
        '\u{2514}' => 0xC0, // └
        '\u{2518}' => 0xD9, // ┘
        '\u{251C}' => 0xC3, // ├
        '\u{2524}' => 0xB4, // ┤
        '\u{252C}' => 0xC2, // ┬
        '\u{2534}' => 0xC1, // ┴
        '\u{253C}' => 0xC5, // ┼
        // Блоки и тени
        '\u{2588}' => 0xDB, // █
        '\u{2591}' => 0xB0, // ░
        '\u{2592}' => 0xB1, // ▒
        '\u{2593}' => 0xB2, // ▓
        '\u{25A0}' => 0xFE, // ■
        // Стрелки и маркеры
        '\u{2190}' => 0x1B, // ←
        '\u{2191}' => 0x18, // ↑
        '\u{2192}' => 0x1A, // →
        '\u{2193}' => 0x19, // ↓
        '\u{00B7}' => 0xFA, // ·
        '\u{2014}' | '\u{2013}' => 0xC4, // — / – → ─
        '\u{00B0}' => 0xF8, // °
        '\u{00B1}' => 0xF1, // ±
        '\u{2265}' => 0xF2, // ≥
        '\u{2264}' => 0xF3, // ≤
        _ => 0,
    }
}

