    /// Пересоздаёт RAM-тень текстовой сетки под текущие cols/rows.
    ///
    /// ВАЖНО: `Console::new()` вызывается ДО `memory::init()` (нужен вывод на
    /// экран уже с первых строк), а куча в этот момент ещё не создана. Поэтому
    /// до инициализации кучи тень не выделяется: консоль работает «медленным»
    /// путём, рисуя прямо во фреймбуфер. После `memory::init()` boot вызывает
    /// `rebuild_cells()`, и тень включается.
    fn reset_cells(&mut self) {
        let (heap_start, heap_end) = crate::memory::heap::region();
        if heap_end <= heap_start {
            self.cells.clear();
            self.cells_valid.set(false);
            return;
        }

        let count = self.cols.saturating_mul(self.rows);
        self.cells.clear();
        self.cells.resize(
            count,
            TextCell { ch: b' ', fg: self.fg_color, bg: self.bg_color },
        );
        self.cells_valid.set(true);
    }

    /// Перестроить тень ячеек (вызывается после инициализации кучи).
    pub(crate) fn rebuild_cells(&mut self) {
        self.reset_cells();
    }

    /// Последняя строка, в которой есть непробельная ячейка.
    fn last_used_row(&self) -> usize {
        if self.cells.len() != self.cols * self.rows {
            return self.rows.saturating_sub(1);
        }
        let mut row = self.rows;
        while row > 0 {
            row -= 1;
            let base = row * self.cols;
            if self.cells[base..base + self.cols]
                .iter()
                .any(|c| c.ch != b' ' && c.ch != 0)
            {
                return row;
            }
        }
        0
    }

    /// Выделить буфер одной текстовой строки (FONT_HEIGHT пиксельных строк).
    ///
    /// Делается после инициализации кучи: до неё `Vec` недоступен, и
    /// `redraw_from_cells` работает старым поштучным путём.
    pub fn alloc_staging(&mut self) {
        if self.rows == 0 || self.width == 0 {
            return;
        }
        // Две пары пикселей на u64: строка шириной `width` требует width/2
        // слов. При нечётной ширине буфер не нужен — останется медленный путь.
        if self.width % 2 != 0 {
            self.staging = Vec::new();
            return;
        }
        let needed = FONT_HEIGHT * (self.width / 2);
        if self.staging.len() != needed {
            self.staging = alloc::vec![0u64; needed];
        }
    }

    /// Очищает весь экран фоновым цветом
    pub fn clear(&mut self) {
        let total_pixels = self.height * self.pitch;
        let bg = crate::display::color_to_native(self.bg_color, self.pixel_format);
        unsafe {
            // Создаём срез и заполняем его за одну операцию (оптимизируется в memset/stosd)
            let slice = core::slice::from_raw_parts_mut(self.fb_addr, total_pixels);
            slice.fill(bg);
        }
        // Очистка экрана при WC-памяти тоже требует барьера.
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        self.reset_cells();
        self.cursor_col = 0;
        self.cursor_row = 0;
        self.painted_max = 0;
        // Курсор залит вместе с экраном.
        self.cursor_painted = false;
        // Экран только что залит целиком: отложенная перерисовка не нужна.
        // Без этого флага `draw_char_at` продолжал считать экран «отставшим»
        // и не рисовал символы — полноэкранные программы (редактор)
        // показывали старую картинку вместо своего содержимого.
        self.pending = false;
    }

    /// Рисует один символ в позиции (col, row)
    pub fn draw_char_at(&mut self, ch: char, col: usize, row: usize, fg: u32, bg: u32) {
        // Если в эту ячейку нарисовано подчёркивание курсора, сначала вернём
        // её содержимое: иначе «ячейка не изменилась» ниже отменит запись, и
        // подчёркивание останется в фреймбуфере навсегда. Сравнивать нужно с
        // той ячейкой, где курсор РЕАЛЬНО нарисован, а не с текущей позицией:
        // `clear_from` двигает позицию до того, как стирает.
        if self.cursor_painted && self.cursor_painted_at == (col, row) {
            self.undraw_cursor();
        }

        if col >= self.cols || row >= self.rows {
            return;
        }

        // Шрифт — CP437 (0..255). Раньше любой символ вне Latin-1 рисовался
        // как пустая ячейка, поэтому `tree`, `ps` и таблицы теряли
        // разделители: "├── " превращалось в пробелы. Переводим рамки и
        // частые символы в их CP437-коды.
        let font_index = if (ch as usize) < 256 {
            ch as usize
        } else {
            cp437_index(ch) as usize
        };

        let cell = TextCell { ch: font_index as u8, fg, bg };
        if self.cells_valid.get() {
            let index = row * self.cols + col;
            if let Some(slot) = self.cells.get_mut(index) {
                // Ячейка уже содержит этот символ с этими цветами: пиксели в
                // фреймбуфере те же. Пропуск экономит 64 записи на символ —
                // это частый случай при перерисовке строки и прокрутке.
                if *slot == cell {
                    return;
                }
                *slot = cell;
            }
            // Экран отстал (идёт массовый вывод): рисовать по пикселю сейчас
            // бессмысленно — следующая прокрутка всё равно перерисует экран
            // целиком. Достаточно обновить тень.
            if self.pending {
                return;
            }
        }
        self.draw_cell_pixels(cell, col, row);
    }

    /// Рисует пиксели одной ячейки.
    ///
    /// Цвета конвертируются ОДИН раз на символ, а не на каждый из 128 пикселей
    /// (раньше `color_to_native` вызывался 128 раз на символ).
    ///
    /// Строка глифа пишется пакетно: `expand_line` собирает 4 u64 (по два
    /// пикселя), `write_glyph_row` отдаёт их 4 записями вместо 8. Итого
    /// 64 записи на символ вместо 128.
    fn draw_cell_pixels(&self, cell: TextCell, col: usize, row: usize) {
        let fg = crate::display::color_to_native(cell.fg, self.pixel_format);
        let bg = crate::display::color_to_native(cell.bg, self.pixel_format);
        self.draw_cell_pixels_native(cell.ch, fg, bg, col, row);
        // При WC-памяти записи копятся в write-combining буферах. Без барьера
        // они доходят до экрана когда захотят (или не доходят вовсе, если
        // буфер не заполнился) — снаружи это выглядит как зависание.
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
    }

    /// То же, но цвета уже в нативном формате.
    ///
    /// Нужно для прокрутки: там перерисовываются тысячи ячеек, и вызывать
    /// `color_to_native` на каждую (дважды) — заметная доля стоимости.
    fn draw_cell_pixels_native(&self, ch: u8, fg: u32, bg: u32, col: usize, row: usize) {
        let start_x = col * FONT_WIDTH;
        let start_y = row * FONT_HEIGHT;
        if start_x >= self.width || start_y >= self.height {
            return;
        }

        // Сколько пикселей строки влезает по ширине (обычно все 8).
        let row_len = FONT_WIDTH.min(self.width - start_x);

        // Пробел — самый частый символ при прокрутке: заливаем построчно срезом.
        if ch == b' ' {
            for dy in 0..FONT_HEIGHT {
                let pixel_y = start_y + dy;
                if pixel_y >= self.height {
                    break;
                }
                unsafe {
                    let row_ptr = self.fb_addr.add(pixel_y * self.pitch + start_x);
                    core::slice::from_raw_parts_mut(row_ptr, row_len).fill(bg);
                }
            }
            return;
        }

        let glyph = &FONT_DATA[ch as usize];
        for dy in 0..FONT_HEIGHT {
            let pixel_y = start_y + dy;
            if pixel_y >= self.height {
                break;
            }
            let words = expand_line(glyph[dy], fg, bg);
            unsafe {
                let row_ptr = self.fb_addr.add(pixel_y * self.pitch + start_x);
                write_glyph_row(row_ptr, &words, row_len);
            }
        }
    }

    /// Печатает символ в текущей позиции курсора с автопереносом
    pub fn put_char(&mut self, ch: char) {
        crate::serial::mirror_console_char(ch);
        self.put_char_from_serial(ch);
    }

    pub(crate) fn put_char_from_serial(&mut self, ch: char) {
        match ch {
            '\n' => {
                self.cursor_col = 0;
                self.cursor_row += 1;
            }
            '\r' => {
                self.cursor_col = 0;
            }
            '\x08' => {
                if self.cursor_col > 0 {
                    self.cursor_col -= 1;
                }
            }
            '\t' => {
                let next_tab = (self.cursor_col / 4 + 1) * 4;
                self.cursor_col = next_tab.min(self.cols - 1);
            }
            _ => {
                self.draw_char_at(ch, self.cursor_col, self.cursor_row, self.fg_color, self.bg_color);
                self.cursor_col += 1;
                if self.cursor_col >= self.cols {
                    self.cursor_col = 0;
                    self.cursor_row += 1;
                }
            }
        }

        // Скроллинг
        if self.cursor_row >= self.rows {
            self.scroll();
        }
        // НЕ рисуем курсор здесь — курсор рисуется только
        // через update_cursor_blink() в главном цикле shell
    }

    /// Печатает строку
    pub fn print(&mut self, s: &str) {
        for ch in s.chars() {
            self.put_char(ch);
        }
    }

    /// Печатает строку с заданным цветом
    pub fn print_colored(&mut self, s: &str, fg: u32) {
        let old_fg = self.fg_color;
        self.fg_color = fg;
        self.print(s);
        self.fg_color = old_fg;
    }

    /// Устанавливает текущий цвет (остаётся до следующего set_fg / print_colored)
    pub fn set_fg(&mut self, fg: u32) {
        self.fg_color = fg;
    }

    /// Установить формат пикселей для конвертации цветов
    pub fn set_pixel_format(&mut self, format: crate::display::PixelFormat) {
        self.pixel_format = format;
    }

    /// Получить текущий формат пикселей
    pub fn pixel_format(&self) -> crate::display::PixelFormat {
        self.pixel_format
    }

    /// Печатает один символ в framebuffer + mirror в serial
    pub fn print_char(&mut self, ch: char) {
        match ch {
            '\n' => {
                self.cursor_col = 0;
                self.cursor_row += 1;
                crate::serial::mirror_console_char('\n');
            }
            '\r' => {
                self.cursor_col = 0;
            }
            '\x01'..='\x04' => {
                // Спец-коды neofetch: только framebuffer (не mirror)
            }
            _ => {
                if (self.cursor_col + 1) * FONT_WIDTH > self.width {
                    self.cursor_col = 0;
                    self.cursor_row += 1;
                }
                if self.cursor_row * FONT_HEIGHT >= self.height {
                    self.scroll();
                    self.cursor_row = self.height / FONT_HEIGHT - 1;
                }
                self.draw_char_at(ch, self.cursor_col, self.cursor_row, self.fg_color, self.bg_color);
                self.cursor_col += 1;
                crate::serial::mirror_console_char(ch);
            }
        }
    }

    /// Прокрутка экрана на одну текстовую строку вверх.
    ///
    /// # Почему здесь больше нет memmove по фреймбуферу
    ///
    /// Раньше сдвиг делался `core::ptr::copy` прямо по видеопамяти. Это
    /// работало только в теории: `copy` — это memmove, он сначала **читает**
    /// источник, а фреймбуфер на реальном железе отображён как write-combining
    /// или uncached MMIO. Чтение из WC-памяти не комбинируется: каждый из
    /// ~1 000 000 пикселей уходил отдельной транзакцией по шине, и одна
    /// прокрутка стоила десятки-сотни миллисекунд.
    ///
    /// Отсюда ровно тот симптом, который виден на железе: пока курсор ниже
    /// последней строки, `scroll()` не вызывается вообще и строка печатается
    /// мгновенно; как только экран заполнен, прокрутка идёт на каждый перевод
    /// строки — и вывод «замедляется с каждой строкой». В QEMU дефект не
    /// проявлялся, потому что эмулятор отвечает на MMIO мгновенно.
    ///
    /// Теперь источник — RAM-тень `cells`: сдвиг идёт по обычной памяти, а во
    /// фреймбуфер только пишем. `redraw_from_cells` дополнительно склеивает
    /// подряд идущие пробельные ячейки в одну заливку, поэтому пустая часть
    /// экрана перерисовывается почти бесплатно.
    ///
    /// Если тень недоступна (`cells_valid == false` — экран рисовался
    /// примитивами напрямую, например gfx-демо), остаётся старый путь со
    /// сдвигом по видеопамяти: медленный, но корректный, и случается редко.
    fn scroll(&mut self) {
        if self.rows == 0 || self.cols == 0 {
            return;
        }

        let can_redraw = self.cells_valid.get() && self.cells.len() == self.cols * self.rows;

        // Медленный MMIO-фреймбуфер: сдвиг только в тени, а перерисовка —
        // отложенная. Экран всё равно не успевает за потоком вывода: пока
        // `cat` печатает, обновлять его чаще 25 раз в секунду бессмысленно,
        // а каждый проход стоит десятки миллисекунд на uncached памяти.
        if can_redraw && !self.fb_is_ram.get() {
            self.cells.copy_within(self.cols.., 0);
            let blank = TextCell { ch: b' ', fg: self.fg_color, bg: self.bg_color };
            let last_row = (self.rows - 1) * self.cols;
            for cell in &mut self.cells[last_row..] {
                *cell = blank;
            }
            // Содержимое уехало вверх, вместе с ним и пиксели курсора.
            self.cursor_painted = false;
            self.pending = true;
            self.flush_if_due(false);
            self.cursor_row = self.rows - 1;
            return;
        }

        // RAM-фреймбуфер (QEMU, часть VM): memmove дешевле — одна операция на
        // пиксель вместо сборки глифов. Здесь же оказываемся, когда тени нет
        // (`cells_valid == false`): тогда это единственный корректный путь.
        //
        // memmove сдвигает и пиксели курсора, поэтому флаг снимаем: иначе
        // `undraw_cursor` потом «восстанавливал» бы ячейку там, где курсора
        // уже нет.
        self.cursor_painted = false;
        let lines_to_move = FONT_HEIGHT;
        let shift_pixels = lines_to_move * self.pitch;

        if self.height > lines_to_move {
            let pixels_to_move = (self.height - lines_to_move) * self.pitch;
            unsafe {
                // copy безопасно работает с перекрывающимися областями (memmove).
                core::ptr::copy(
                    self.fb_addr.add(shift_pixels),
                    self.fb_addr,
                    pixels_to_move,
                );

                // Очищаем нижние строки фоновым цветом.
                let slice = core::slice::from_raw_parts_mut(
                    self.fb_addr.add(pixels_to_move),
                    shift_pixels,
                );
                slice.fill(crate::display::color_to_native(self.bg_color, self.pixel_format));
            }
        }

        // Синхронизируем RAM-тень: сдвиг строк и пустая последняя строка.
        if self.cells.len() == self.cols * self.rows {
            self.cells.copy_within(self.cols.., 0);
            let blank = TextCell { ch: b' ', fg: self.fg_color, bg: self.bg_color };
            let last_row = (self.rows - 1) * self.cols;
            for cell in &mut self.cells[last_row..] {
                *cell = blank;
            }
        }

        self.cursor_row = self.rows - 1;
    }

    /// Перевести фреймбуфер в write-combining (PAT) и запомнить результат.
    ///
    /// Зачем: на реальном железе GOP-фреймбуфер отображён как uncached/UC.
    /// Прокрутка пишет ~1 млн пикселей, и при UC каждая запись уходит
    /// отдельной транзакцией — отсюда «пока экран не заполнен, всё быстро,
    /// а как заполнился, каждая строка тормозит». С WC записи склеиваются в
    /// пакеты, и тот же объём уходит на порядок быстрее.
    ///
    /// Чтение из WC по-прежнему дорогое, поэтому `scroll()` продолжает идти
    /// через RAM-тень `cells` и только пишет в видеопамять.
    pub fn enable_write_combining(&mut self) {
        if self.fb_addr.is_null() || self.pitch == 0 || self.height == 0 {
            return;
        }
        self.pat_ok = crate::memory::paging::enable_pat_write_combining();
        if !self.pat_ok {
            return;
        }
        let bytes = (self.pitch * self.height * 4) as u64;
        let report = crate::memory::paging::set_write_combining(self.fb_addr as u64, bytes);
        self.wc_pages = report.changed;
        self.wc_already = report.already;
        self.wc_unmapped = report.unmapped;
        self.wc_leaf_flags = report.leaf_flags;

        // PAT не переопределяет MTRR: если фреймбуфер покрыт диапазоном UC,
        // записи всё равно уходят по одной транзакции. Добавляем более
        // специфичный диапазон WC на сам фреймбуфер — по правилам MTRR
        // побеждает более узкий диапазон, поэтому остальные MMIO-области
        // остаются как были.
        //
        // Раньше это выглядело как зависание загрузки, но причина была не в
        // MTRR: после смены типа памяти записи уходили в write-combining
        // буферы и без `sfence` не доходили до экрана. Теперь барьер стоит
        // после каждой отрисовки.
        // MTRR на загрузке не меняем: правка MSR/wbinvd подвешивает boot
        // (см. `diag mtrr wc`). Здесь только читаем текущий тип, чтобы
        // отчёт `diag fb` показывал реальную причину.
        if let Some(phys) = crate::memory::paging::virt_to_phys(self.fb_addr as u64) {
            self.mtrr_type = crate::memory::mtrr::covering_type(phys)
                .unwrap_or(crate::memory::mtrr::default_type());
            self.mtrr_before = self.mtrr_type;
        }
        // Печать откладывается: `init_boot_console` вызывается до
        // `[BOOT] Step 1`, а boot-лог обязан начинаться с него (иначе не
        // отличить норму от регрессии с нулями в начале файла).
        self.wc_report_pending = true;
    }

    /// Выставить WC на диапазон фреймбуфера через MTRR.
    ///
    /// Возвращает `(успех, тип до, тип после)`. Вызывается командой
    /// `diag mtrr wc`: менять MTRR на загрузке опасно, а здесь пользователь
    /// видит отчёт и может сравнить замеры до и после.
    pub fn apply_mtrr_wc(&mut self) -> (bool, u8, u8) {
        let bytes = (self.pitch * self.height * 4) as u64;
        let Some(phys) = crate::memory::paging::virt_to_phys(self.fb_addr as u64) else {
            return (false, 0xFF, 0xFF);
        };
        let before = crate::memory::mtrr::covering_type(phys)
            .unwrap_or(crate::memory::mtrr::default_type());
        let ok = crate::memory::mtrr::set_write_combining(phys, bytes);
        let after = crate::memory::mtrr::covering_type(phys)
            .unwrap_or(crate::memory::mtrr::default_type());
        self.mtrr_type = after;
        (ok, before, after)
    }

    /// Сколько байт занимает staging-буфер строки (0 — быстрый путь выключен).
    pub fn staging_bytes(&self) -> usize {
        self.staging.len() * core::mem::size_of::<u64>()
    }

    /// Состояние отрисовки для `diag fb`:
    /// `(PAT, тип MTRR фреймбуфера, изменено, уже WC, вне отображения, флаги)`.
    pub fn write_combining_state(&self) -> (bool, u8, usize, usize, usize, u64) {
        (
            self.pat_ok,
            self.mtrr_type,
            self.wc_pages,
            self.wc_already,
            self.wc_unmapped,
            self.wc_leaf_flags,
        )
    }

    /// Замер стоимости перерисовки экрана из текстовой тени: ровно та работа,
    /// которую делает каждая прокрутка.
    ///
    /// Возвращает микросекунды на один проход. Нужен, чтобы на железе без
    /// serial было видно, во что обходится прокрутка и помог ли WC, а не
    /// гадать по ощущениям.
    /// Собрать одну текстовую строку в `staging` (без записи в фреймбуфер).
    ///
    /// Вынесено из `redraw_from_cells`, чтобы `diag fb` мог измерить именно
    /// стоимость сборки: если она доминирует, оптимизировать надо её, а не
    /// память фреймбуфера.
    fn build_row_into_staging(&mut self, row: usize, blank_word: u64) {
        let width = self.width;
        let words_per_row = width / 2;
        if self.staging.len() != FONT_HEIGHT * words_per_row || row >= self.rows {
            return;
        }
        let base = row * self.cols;
        self.staging.fill(blank_word);

        let mut cached_fg = u32::MAX;
        let mut cached_bg = u32::MAX;
        let mut native_fg = 0u32;
        let mut native_bg = 0u32;

        for col in 0..self.cols {
            let cell = self.cells[base + col];
            if cell.ch == b' ' || cell.ch == 0 {
                continue;
            }
            let start_x = col * FONT_WIDTH;
            if start_x >= width {
                break;
            }
            if cell.fg != cached_fg || cell.bg != cached_bg {
                cached_fg = cell.fg;
                cached_bg = cell.bg;
                native_fg = crate::display::color_to_native(cell.fg, self.pixel_format);
                native_bg = crate::display::color_to_native(cell.bg, self.pixel_format);
            }
            let glyph = &FONT_DATA[cell.ch as usize];
            let first_word = start_x / 2;
            let avail = words_per_row.saturating_sub(first_word);
            let n = (FONT_WIDTH / 2).min(avail);
            if n == 0 {
                break;
            }
            // Прямая запись по указателю: индексация `Vec` внутри двойного
            // цикла давала проверку границ на каждое слово и в сумме стоила
            // больше, чем вся запись строки во фреймбуфер (замер: 2 млн
            // циклов на сборку строки против 3 тысяч на копирование).
            // Границы проверены выше: first_word + n <= words_per_row.
            let base_ptr = self.staging.as_mut_ptr();
            for dy in 0..FONT_HEIGHT {
                let words = expand_line(glyph[dy], native_fg, native_bg);
                unsafe {
                    let dst = base_ptr.add(dy * words_per_row + first_word);
                    for k in 0..n {
                        core::ptr::write(dst.add(k), words[k]);
                    }
                }
            }
        }
    }

    /// Сколько стоит сдвинуть текстовую сетку на `lines` строк.
    ///
    /// Работает на **отдельной копии** сетки и не трогает ни живую тень, ни
    /// фреймбуфер. Раньше здесь заполнялась настоящая `cells` и вызывался
    /// `scroll()`, который на медленном фреймбуфере перерисовывал экран —
    /// отсюда и заливка экрана символами `x` после `diag fb`.
    pub fn bench_scroll(&mut self, lines: usize) -> (u64, u64) {
        if lines == 0 || self.cols == 0 || self.rows == 0 {
            return (0, 0);
        }

        let blank = TextCell { ch: b' ', fg: self.fg_color, bg: self.bg_color };
        let cell = TextCell { ch: b'x', fg: self.fg_color, bg: self.bg_color };
        let mut scratch = alloc::vec![cell; self.cols * self.rows];
        for row in 0..self.rows {
            scratch[row * self.cols + self.cols - 1] = blank;
        }

        let columns = self.cols;
        let rows = self.rows;
        let us_start = crate::timer::uptime_us();
        let start = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..lines {
            scratch.copy_within(columns.., 0);
            let last = (rows - 1) * columns;
            for slot in &mut scratch[last..] {
                *slot = blank;
            }
        }
        let cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(start);
        let us = crate::timer::uptime_us().saturating_sub(us_start);

        (cycles / lines as u64, us / lines as u64)
    }

    /// Стоимость отрисовки одного символа в staging (без записи в экран).
    ///
    /// Ровно то, что происходит на каждый символ вывода. Ничего не меняет:
    /// пишет в buffer строки, живая тень и фреймбуфер не трогаются.
    pub fn bench_char_render(&mut self, chars: u32) -> u64 {
        let words_per_row = self.width / 2;
        if chars == 0 || words_per_row == 0 || self.staging.len() < FONT_HEIGHT * words_per_row {
            return 0;
        }
        let fg = crate::display::color_to_native(self.fg_color, self.pixel_format);
        let bg = crate::display::color_to_native(self.bg_color, self.pixel_format);
        let glyph = &FONT_DATA[b'W' as usize];

        let start = unsafe { core::arch::x86_64::_rdtsc() };
        let base = self.staging.as_mut_ptr();
        for _ in 0..chars {
            for dy in 0..FONT_HEIGHT {
                let words = expand_line(glyph[dy], fg, bg);
                unsafe {
                    let dst = base.add(dy * words_per_row);
                    for k in 0..4.min(words_per_row) {
                        core::ptr::write(dst.add(k), words[k]);
                    }
                }
            }
        }
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(start) / chars as u64
    }

    /// Стоимость одного полного прохода перерисовки из тени: ровно то, что
    /// делает `scroll()` на медленном фреймбуфере.
    pub fn bench_full_repaint(&mut self, iterations: u32) -> (u64, u64) {
        if iterations == 0 || self.cells_valid.get() == false {
            return (0, 0);
        }
        let us_start = crate::timer::uptime_us();
        let start = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..iterations {
            self.redraw_from_cells();
        }
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        let cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(start);
        let us = crate::timer::uptime_us().saturating_sub(us_start);
        (cycles / iterations as u64, us / iterations as u64)
    }

    /// Стоимость записи всего экрана из `staging` во фреймбуфер, в циклах.
    ///
    /// Это нижняя граница любой стратегии прокрутки: даже если ничего не
    /// пересобирать, экран надо как-то переписать. Если это число велико,
    /// виноват memory type фреймбуфера, а не код отрисовки.
    pub fn bench_screen_write(&mut self, iterations: u32) -> u64 {
        let width = self.width;
        let words_per_row = width / 2;
        if iterations == 0 || width < 32 || self.staging.len() != FONT_HEIGHT * words_per_row {
            return 0;
        }
        let src = self.staging.as_ptr();
        let start = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..iterations {
            for py in 0..self.height {
                unsafe {
                    let dst = self.fb_addr.add(py * self.pitch) as *mut u64;
                    core::ptr::copy_nonoverlapping(src, dst, words_per_row);
                }
            }
        }
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        let cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(start) / iterations as u64;

        // Замер затирает весь экран строкой из staging. Восстанавливаем его
        // целиком: без этого ниже `painted_max` оставались чужие пиксели, и
        // `draw_char_at` считал пробелы уже нарисованными — отсюда «x» вместо
        // пробелов в выводе команды.
        self.cursor_painted = false;
        self.pending = false;
        self.painted_max = self.rows.saturating_sub(1);
        self.redraw_from_cells();

        cycles
    }

    /// Стоимость сборки строки при заданной плотности текста.
    ///
    /// Нужен, чтобы отделить «пустая строка» от «строка целиком из символов»:
    /// прокрутка заполненного экрана тормозит именно из-за вторых, и без
    /// такого замера не видно, во что обходится одна ячейка.
    pub fn bench_row_density(&mut self, cells_filled: usize) -> u64 {
        let width = self.width;
        let words_per_row = width / 2;
        if width < 32 || self.staging.len() != FONT_HEIGHT * words_per_row || self.rows == 0 {
            return 0;
        }
        let blank = crate::display::color_to_native(self.bg_color, self.pixel_format);
        let blank_word = ((blank as u64) << 32) | blank as u64;

        let saved_row: alloc::vec::Vec<TextCell> =
            self.cells[0..self.cols].to_vec();

        // Готовим строку 0 с нужным числом непробельных ячеек.
        let base = 0usize;
        for col in 0..self.cols {
            let ch = if col < cells_filled { b'x' } else { b' ' };
            self.cells[base + col] = TextCell { ch, fg: self.fg_color, bg: self.bg_color };
        }

        const ITERS: u32 = 50;
        let start = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..ITERS {
            self.build_row_into_staging(0, blank_word);
        }
        let cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(start);

        // Возвращаем строку как была.
        self.cells[base..base + self.cols].copy_from_slice(&saved_row);

        cycles / ITERS as u64
    }

    /// Стоимость сборки строки и её записи — по отдельности, в циклах TSC.
    ///
    /// `(build_cycles, fb_copy_cycles, ram_copy_cycles)`.
    pub fn bench_row_build_and_copy(&mut self, iterations: u32) -> (u64, u64, u64) {
        let width = self.width;
        if iterations == 0 || width < 32 || self.staging.len() < width / 2 {
            return (0, 0, 0);
        }
        let words = width / 2;
        let blank = crate::display::color_to_native(self.bg_color, self.pixel_format);
        let blank_word = ((blank as u64) << 32) | blank as u64;

        let t = unsafe { core::arch::x86_64::_rdtsc() };
        for i in 0..iterations {
            self.build_row_into_staging((i as usize) % self.rows.max(1), blank_word);
        }
        let build = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(t);

        let mut ram_dst = alloc::vec![0u64; words];
        let src = self.staging.as_ptr();
        let t = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..iterations {
            unsafe { core::ptr::copy_nonoverlapping(src, ram_dst.as_mut_ptr(), words) };
        }
        let ram_copy = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(t);

        let t = unsafe { core::arch::x86_64::_rdtsc() };
        for i in 0..iterations {
            let py = (i as usize) % self.height.max(1);
            unsafe {
                let dst = self.fb_addr.add(py * self.pitch) as *mut u64;
                core::ptr::copy_nonoverlapping(src, dst, words);
            }
        }
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        let fb_copy = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(t);

        let n = iterations as u64;
        (build / n, fb_copy / n, ram_copy / n)
    }

    /// Стоимость копирования одной текстовой строки во фреймбуфер и в RAM.
    ///
    /// Возвращает `(fb_cycles, ram_cycles)` на одно копирование строки.
    /// Нужен, чтобы отличить «медленная видеопамять» от «медленный код»:
    /// если `fb_cycles` намного больше `ram_cycles`, виноват memory type
    /// фреймбуфера (нужен WC), а если они близки — искать надо в отрисовке.
    pub fn bench_row_copy(&mut self, iterations: u32) -> (u64, u64) {
        let width = self.width;
        if iterations == 0 || width < 16 || self.staging.len() < width / 2 {
            return (0, 0);
        }
        let words = width / 2;

        // Источник и приёмник в RAM.
        let mut ram_dst = alloc::vec![0u64; words];
        let src = self.staging.as_ptr();

        let ram_start = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..iterations {
            unsafe {
                core::ptr::copy_nonoverlapping(src, ram_dst.as_mut_ptr(), words);
            }
        }
        let ram_cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(ram_start);

        let fb_start = unsafe { core::arch::x86_64::_rdtsc() };
        for i in 0..iterations {
            let py = (i as usize) % self.height.max(1);
            unsafe {
                let dst = self.fb_addr.add(py * self.pitch) as *mut u64;
                core::ptr::copy_nonoverlapping(src, dst, words);
            }
        }
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        let fb_cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(fb_start);

        (fb_cycles / iterations as u64, ram_cycles / iterations as u64)
    }

    /// Возвращает `(циклы TSC на проход, микросекунды на проход)`.
    ///
    /// TSC здесь основной источник: у `uptime_us()` зависит от выбранного
    /// источника часов (HPET/PIT), и при ошибке в его пересчёте замер врал бы
    /// в разы. Циклы позволяют проверить число независимо.
    pub fn bench_redraw(&mut self, iterations: u32) -> (u64, u64) {
        if iterations == 0 || !self.cells_valid.get() {
            return (0, 0);
        }
        let us_start = crate::timer::uptime_us();
        let start = unsafe { core::arch::x86_64::_rdtsc() };
        for _ in 0..iterations {
            self.redraw_from_cells();
        }
        // Записи в WC-память завершаются асинхронно: без барьера замер
        // показывал бы только время постановки в буферы.
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
        let cycles = unsafe { core::arch::x86_64::_rdtsc() }.wrapping_sub(start);
        let us = crate::timer::uptime_us().saturating_sub(us_start);
        (cycles / iterations as u64, us / iterations as u64)
    }

    /// Перерисовать экран, если он отстал и прошло достаточно времени.
    ///
    /// `force` — перерисовать немедленно (перед приглашением, после команды,
    /// при выходе из режима массового вывода).
    ///
    /// Интервал выбран 40 мс: это ~25 обновлений в секунду, глаз не замечает
    /// разницы, а число проходов по 5.7 МБ падает на порядок.
    pub fn flush_if_due(&mut self, force: bool) {
        if !self.pending {
            return;
        }
        let now = crate::timer::uptime_ms();
        if !force && now.saturating_sub(self.last_flush_ms) < 40 {
            return;
        }
        self.last_flush_ms = now;
        self.pending = false;
        self.redraw_from_cells();
    }

    /// Есть ли непринятые изменения на экране (для тестов и отладки).
    pub fn has_pending_redraw(&self) -> bool {
        self.pending
    }

    /// Перерисовывает экран из RAM-тени `cells`, не читая видеопамять.
    ///
    /// Каждая текстовая строка собирается в `staging` (обычная RAM), а затем
    /// уходит во фреймбуфер одной широкой копией на пиксельную строку.
    ///
    /// # Почему не по пикселю
    ///
    /// Раньше глиф писался 64 отдельными `write_volatile::<u64>`. Прокрутка
    /// полного экрана 1280x800 — это ~500 000 транзакций: замер на QEMU дал
    /// 1.02 млрд циклов (~400 мс) за один проход, а на железе каждая такая
    /// запись ещё и уходит по шине. Отсюда ровно жалоба «пока экран не
    /// заполнен — мгновенно, как дошло до низа — тормозит».
    ///
    /// Сборка в RAM и 16 копий по 5 КБ на строку (вместо 8000 записей)
    /// снимают и накладные расходы MMIO, и стоимость на реальном железе.
    fn redraw_from_cells(&mut self) {
        if !self.cells_valid.get() || self.cells.len() != self.cols * self.rows {
            return;
        }

        let blank_bg = crate::display::color_to_native(self.bg_color, self.pixel_format);
        let width = self.width;
        let words_per_row = width / 2;
        let use_staging = width % 2 == 0
            && self.staging.len() == FONT_HEIGHT * words_per_row;

        // Граница прорисовки: ниже последней строки с текстом ничего нет —
        // и в тени, и в фреймбуфере там уже фон. Раньше перерисовывались все
        // `rows`, поэтому прокрутка стоила одинаково независимо от заполнения.
        let last_used = self.last_used_row();
        let last_row = last_used.max(self.painted_max).min(self.rows.saturating_sub(1));
        self.painted_max = last_used;

        if use_staging {
            // Пара пикселей в одном u64 — столько же запишу в фреймбуфер,
            // но вдвое меньшим числом операций.
            let blank_word = ((blank_bg as u64) << 32) | blank_bg as u64;

            for row in 0..=last_row {
                let base = row * self.cols;
                self.staging.fill(blank_word);

                for col in 0..self.cols {
                    let cell = self.cells[base + col];
                    if cell.ch == b' ' || cell.ch == 0 {
                        continue;
                    }
                    let start_x = col * FONT_WIDTH;
                    if start_x >= width {
                        break;
                    }
                    let fg = crate::display::color_to_native(cell.fg, self.pixel_format);
                    let bg = crate::display::color_to_native(cell.bg, self.pixel_format);
                    let glyph = &FONT_DATA[cell.ch as usize];
                    let first_word = start_x / 2;
                    let full_words = (FONT_WIDTH / 2).min(words_per_row.saturating_sub(first_word));
                    for dy in 0..FONT_HEIGHT {
                        // `expand_line` уже отдаёт 8 пикселей как 4 u64 —
                        // ровно то, что нужно положить в строку-тень.
                        let words = expand_line(glyph[dy], fg, bg);
                        let dst = &mut self.staging[dy * words_per_row + first_word..];
                        let n = full_words.min(4);
                        dst[..n].copy_from_slice(&words[..n]);
                    }
                }

                for dy in 0..FONT_HEIGHT {
                    let py = row * FONT_HEIGHT + dy;
                    if py >= self.height {
                        break;
                    }
                    unsafe {
                        let src = self.staging.as_ptr().add(dy * words_per_row);
                        let dst = self.fb_addr.add(py * self.pitch) as *mut u64;
                        // Одна широкая запись на пиксельную строку вместо
                        // 160×8 отдельных volatile-записей.
                        core::ptr::copy_nonoverlapping(src, dst, words_per_row);
                    }
                }
            }
        } else {
            // Фолбэк до инициализации кучи (или нечётная ширина): поштучно.
            for row in 0..=last_row {
                let base = row * self.cols;
                for col in 0..self.cols {
                    let cell = self.cells[base + col];
                    self.draw_cell_pixels_native(
                        cell.ch,
                        crate::display::color_to_native(cell.fg, self.pixel_format),
                        crate::display::color_to_native(cell.bg, self.pixel_format),
                        col,
                        row,
                    );
                }
            }
        }

        // Перерисовали из тени — пикселей курсора на экране больше нет.
        self.cursor_painted = false;

        // WC-записи завершаются асинхронно; барьер делает результат видимым
        // до возврата в вызывающий код (и заодно корректно заканчивает замер).
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
    }

    pub fn set_cursor(&mut self, col: usize, row: usize) {
        self.cursor_col = col;
        self.cursor_row = row;
    }

    /// Рисует блочный курсор в текущей позиции (инвертирует фон)
    pub fn draw_cursor(&mut self) {
        // Сначала убрать предыдущий курсор, если он нарисован в другой ячейке:
        // иначе на экране остаются два подчёркивания.
        if self.cursor_painted {
            self.undraw_cursor();
        }
        if self.cursor_col >= self.cols || self.cursor_row >= self.rows {
            return;
        }
        let x = self.cursor_col * FONT_WIDTH;
        let y = self.cursor_row * FONT_HEIGHT;
        // Underline cursor: рисуем горизонтальную линию 2px внизу ячейки
        let inv_bg = crate::display::color_to_native(!self.bg_color, self.pixel_format);
        // Сплошная строка (0xFF) одного цвета: 4 записи u64 на строку вместо 8 u32.
        let words = expand_line(0xFF, inv_bg, inv_bg);
        let row_len = FONT_WIDTH.min(self.width.saturating_sub(x));
        for dy in [FONT_HEIGHT - 1, FONT_HEIGHT - 2] {
            let py = y + dy;
            if py >= self.height {
                continue;
            }
            unsafe {
                let row_ptr = self.fb_addr.add(py * self.pitch + x);
                write_glyph_row(row_ptr, &words, row_len);
            }
        }
        self.cursor_painted = true;
        self.cursor_painted_at = (self.cursor_col, self.cursor_row);
    }

    /// Убирает подчёркивание, восстанавливая ячейку из текстовой тени.
    ///
    /// Раньше нижние две пиксельные строки заливались фоном. Если курсор
    /// стоял на символе, у глифа съедался низ (у `g`, `p`, `y`, `j`), а
    /// `draw_char_at` не перерисовывал ячейку, потому что тень считала её
    /// целой — дефект оставался навсегда.
    pub fn undraw_cursor(&mut self) {
        if !self.cursor_painted {
            return;
        }
        let (col, row) = self.cursor_painted_at;
        self.cursor_painted = false;
        if col >= self.cols || row >= self.rows {
            return;
        }
        // Восстанавливаем ячейку целиком из тени: так возвращается и символ,
        // который был под курсором.
        let index = row * self.cols + col;
        let cell = self.cells.get(index).copied().unwrap_or(TextCell {
            ch: b' ',
            fg: self.fg_color,
            bg: self.bg_color,
        });
        // Пишем напрямую: `draw_char_at` счёл бы ячейку неизменной и ничего
        // не сделал.
        self.draw_cell_pixels(cell, col, row);
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
    }

    /// Обновление мигания курсора — вызывать периодически.
    ///
    /// Раньше здесь сравнивались IRQ-тики (`TICKS`, 100 Гц) с частотой HPET
    /// (десятки МГц) — интервал получался в миллионы «тиков», и курсор не
    /// мигал никогда. Теперь используется монотонное время в миллисекундах.
    pub fn update_cursor_blink(&mut self) {
        const BLINK_MS: u64 = 500;
        // Экран отстал от тени: рисовать подчёркивание сейчас бессмысленно,
        // ближайшая перерисовка его всё равно затрёт.
        if self.pending {
            return;
        }
        let now = crate::timer::uptime_ms();
        // Первый вызов: рисуем курсор сразу, не ждём полсекунды.
        if self.last_blink_ms == 0 && now > 0 {
            self.last_blink_ms = now;
            self.draw_cursor();
            return;
        }
        if now.saturating_sub(self.last_blink_ms) >= BLINK_MS {
            self.last_blink_ms = now;
            // Состояние берём по факту: нарисован ли курсор в фреймбуфере.
            // Раньше переключалась отдельная «фаза», которая расходилась с
            // пикселями после каждой очистки экрана — отсюда залипшее
            // подчёркивание в строке ввода.
            if self.cursor_painted {
                self.undraw_cursor();
            } else {
                self.draw_cursor();
            }
            self.cursor_blink_state = self.cursor_painted;
        }
    }

    /// Нарисовать блочный курсор: ячейка рисуется с инвертированными цветами.
    ///
    /// Подчёркивание в редакторе почти не видно (под `[`, `_`, пробелом его
    /// не отличить от обычного символа). Блок виден всегда, поэтому
    /// полноэкранные программы используют именно его.
    pub fn draw_block_cursor(&mut self) {
        let (col, row) = (self.cursor_col, self.cursor_row);
        if col >= self.cols || row >= self.rows {
            return;
        }
        let index = row * self.cols + col;
        let Some(cell) = self.cells.get(index).copied() else {
            return;
        };
        // Инверсия: символ рисуется цветом фона на цвете символа.
        self.draw_cell_pixels(cell, col, row);
        let x = col * FONT_WIDTH;
        let y = row * FONT_HEIGHT;
        let glyph = &FONT_DATA[cell.ch as usize];
        let fg = crate::display::color_to_native(cell.bg, self.pixel_format);
        let bg = crate::display::color_to_native(cell.fg, self.pixel_format);
        for dy in 0..FONT_HEIGHT {
            let py = y + dy;
            if py >= self.height {
                break;
            }
            let words = expand_line(glyph[dy], fg, bg);
            let row_len = FONT_WIDTH.min(self.width.saturating_sub(x));
            unsafe {
                let row_ptr = self.fb_addr.add(py * self.pitch + x);
                write_glyph_row(row_ptr, &words, row_len);
            }
        }
        self.cursor_painted = false;
        unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags)) };
    }

    /// Сбросить состояние курсора: следующее `update_cursor_blink` нарисует
    /// его сразу. Вызывается при входе в новую «сессию» ввода.
    pub fn reset_cursor_blink(&mut self) {
        self.cursor_painted = false;
        self.cursor_blink_state = false;
        self.last_blink_ms = 0;
    }

    /// Рисует любой CP437 символ (0-255) по коду байта
    pub fn draw_extended_char(&self, ch: u8, col: usize, row: usize, fg: u32, bg: u32) {
        if col >= self.cols || row >= self.rows {
            return;
        }
        // Символ рисуется мимо текстовой сетки (нет &mut self) — тень устарела.
        self.cells_valid.set(false);
        let font_index = ch as usize;
        let glyph = &FONT_DATA[font_index];
        let start_x = col * FONT_WIDTH;
        let start_y = row * FONT_HEIGHT;
        if start_x >= self.width || start_y >= self.height {
            return;
        }

        // Раньше `color_to_native` вызывался здесь на каждый из 128 пикселей —
        // теперь дважды на символ, а строки пишутся пакетно.
        let fg = crate::display::color_to_native(fg, self.pixel_format);
        let bg = crate::display::color_to_native(bg, self.pixel_format);
        let row_len = FONT_WIDTH.min(self.width - start_x);

        for dy in 0..FONT_HEIGHT {
            let pixel_y = start_y + dy;
            if pixel_y >= self.height {
                break;
            }
            let words = expand_line(glyph[dy], fg, bg);
            unsafe {
                let row_ptr = self.fb_addr.add(pixel_y * self.pitch + start_x);
                write_glyph_row(row_ptr, &words, row_len);
            }
        }
    }

    /// Восстанавливает текстовый режим после графических demo
    pub fn restore_text_mode(&mut self) {
        self.disable_back_buffer();
        self.virtual_width = 0;
        self.virtual_height = 0;
        self.scale_x = 0;
        self.scale_y = 0;
        self.clear();
        self.set_cursor(0, 0);
    }

